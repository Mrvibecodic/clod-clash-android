package com.github.kr328.clash.service.util

/**
 * Длительность текущей сессии для таймера на главном экране.
 *
 * Вынесено отдельной функцией без единого обращения к Android: расчёт времени —
 * это ровно то место, где ошибку видно только на живом устройстве через сутки,
 * поэтому его дешевле проверить тестом.
 *
 * Правило простое: считаем по монотонным часам, а системные оставляем запасным
 * путём на случай, когда монотонной метки нет вовсе — например, в настройках
 * лежит запись от версии приложения, которая её ещё не писала.
 */
object SessionClock {
    /**
     * @param startedAt метка подъёма туннеля по системным часам
     * @param startedElapsed та же метка по монотонным часам
     * @param nowWall текущее время по системным часам
     * @param nowElapsed текущее время по монотонным часам
     */
    fun seconds(
        startedAt: Long,
        startedElapsed: Long,
        nowWall: Long,
        nowElapsed: Long,
    ): Long {
        // Метка больше текущего аптайма — телефон с тех пор перезагружался,
        // сравнивать нечего. Проверка ловит такую метку не всегда (аптайм её
        // рано или поздно перерастёт), и большего тут не нужно: метку читают
        // только при работающей службе, а любой её запуск переписывает обе —
        // после перезагрузки службы нет и читать нечего.
        if (startedElapsed in 1..nowElapsed) {
            return (nowElapsed - startedElapsed) / 1000
        }

        if (startedAt > 0) {
            return ((nowWall - startedAt) / 1000).coerceAtLeast(0)
        }

        return 0
    }
}
