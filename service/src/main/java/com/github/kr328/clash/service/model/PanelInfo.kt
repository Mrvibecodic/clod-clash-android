package com.github.kr328.clash.service.model

import kotlinx.serialization.Serializable

/**
 * Что известно о подписке помимо самого конфига.
 *
 * Файл `panel.json` рядом с `config.yaml` в каталоге профиля пишет ядро при
 * загрузке подписки (`native/config/panel.go`). Файлом, а не колонками в базе:
 * заводить миграцию Room на каждый новый заголовок панели — дорого, а живут эти
 * данные ровно столько же, сколько сам профиль, и обновляются вместе с ним.
 *
 * Все поля со значением по умолчанию: старый профиль, загруженный до появления
 * этого файла, читается как пустой, а не роняет разбор.
 */
@Serializable
data class PanelInfo(
    /** Название подписки от панели (`profile-title`). */
    val title: String = "",
    /** `profile-logo` — адрес логотипа провайдера, уже проверенный на https. */
    val logoUrl: String = "",
    /**
     * Имя файла с логотипом в каталоге профиля, если его удалось скачать.
     * Ядро кладёт картинку рядом с `config.yaml` при обновлении подписки:
     * так она не мигает на холодном старте, работает офлайн и не отдаёт
     * чужому хосту адрес человека на каждой отрисовке экрана.
     */
    val logoFile: String = "",
    /**
     * Объявление провайдера (`announce`) и ссылка «подробнее» к нему.
     *
     * Как и всё остальное, что панель рассказывает о себе, живёт ровно один
     * ответ: снятое провайдером объявление исчезает тем же обновлением, а не
     * висит до переустановки подписки.
     */
    val announce: String = "",
    val announceUrl: String = "",
    val supportUrl: String = "",
    val homeUrl: String = "",
    /** `clod-portal-url` — кнопка «Личный кабинет»; пусто означает «кнопки нет». */
    val portalUrl: String = "",
    /**
     * Остальные ссылки провайдера: бот (`clod-bot-url`), состояние серверов
     * (`clod-monitor-url`) и инструкция (`clod-guide-url`). Пусто — строки нет.
     *
     * Бот отдельно от поддержки намеренно: он выдаёт ссылку, продлевает и
     * отвечает сам, а поддержка — живой человек.
     *
     * Все ссылки (вместе с [supportUrl], [homeUrl] и [portalUrl]) живут ровно
     * один ответ панели: перестала слать — исчезли тем же обновлением. Иначе
     * кабинет прежнего провайдера остался бы на профиле, в который вставили
     * чужую ссылку. Держится только [title]: под ним подписка лежит в списке.
     */
    val botUrl: String = "",
    val monitorUrl: String = "",
    val guideUrl: String = "",
    val promo: String = "",
    val promoUrl: String = "",
    /**
     * Состояние устройства: `active`, `limit`, `not-supported` или пусто,
     * если про устройства ничего не пришло. Разбирается ядром
     * (`native/config/panel.go`).
     */
    val hwidState: String = "",

    /**
     * `clod-hwid-limit` — текст провайдера для карточек «лимит устройств»
     * и «устройство не опознано». Необязательный и отдельный от `announce`:
     * объявление на главной видят все, а это объяснение адресовано одному
     * заблокированному устройству.
     */
    val hwidLimitMessage: String = "",

    /** Сколько устройств разрешено подпиской; 0 — не сказано. */
    val hwidMaxDevices: Int = 0,

    /** Когда обновится трафик, в секундах Unix; 0 — не сказано. */
    val refillDate: Long = 0,

    /**
     * За сколько дней до конца подписки напоминать (`notify-expire-days`)
     * и на каком проценте израсходованного трафика (`notify-traffic-percent`).
     *
     * `null` и пустой список значат РАЗНОЕ. `null` — панель про напоминания
     * ничего не сказала, и клиент берёт свои умолчания. Пустой список — панель
     * напоминания выключила, и молчать надо совсем. Поэтому у полей нет
     * значения-заглушки вроде `emptyList()`.
     */
    val notifyExpireDays: List<Int>? = null,
    val notifyTrafficPercent: List<Int>? = null,

    /**
     * Насколько часы панели опережают часы устройства (секунды) и когда это
     * измерено по часам устройства. Считает ядро по заголовку `Date`.
     */
    val clockSkew: Long = 0,
    val clockSkewAt: Long = 0,

    /**
     * Куда провайдер просит переехать (`new-url` или `new-domain`), уже
     * проверенный ядром адрес. Пусто — переезда не просили.
     */
    val migrateUrl: String = "",

    /**
     * `clod-lock-mode` — провайдер запрещает менять режим туннеля.
     * `null` — панель промолчала, решение остаётся за человеком.
     */
    val lockMode: Boolean? = null,

    /**
     * Настоящих серверов не выдано вовсе: пришли одни узлы-обманки, и ядро
     * их выбросило. Пустой список без объяснения читается как поломка
     * приложения, поэтому факт нужен экрану отдельно.
     */
    val noServers: Boolean = false,

    /**
     * Запасные адреса подписки: `fallback-url` — адрес целиком,
     * `fallback-domain` — только хост, который подставляется в основной адрес.
     *
     * Ходит по ним ядро и только когда основной адрес не ответил; сохранённый
     * адрес подписки при этом не меняется. Приложению они нужны разве что
     * для отладки — решение принимается в Go.
     */
    val fallbackUrl: String = "",
    val fallbackDomain: String = "",

    /**
     * Описания узлов из конфигурации (`serverDescription`) по именам узлов.
     *
     * Ядро о таком поле не знает и через API его не отдаёт, поэтому описания
     * собираются при разборе конфигурации и лежат здесь — рядом с составом
     * групп, который нужен по той же причине.
     */
    val descriptions: Map<String, String> = emptyMap(),

    /**
     * `clod-show-0hosts` — провайдер просит НЕ прятать узлы-обманки.
     *
     * Наши экраны «серверов нет» — поведение по умолчанию, заголовок их
     * отключает. Экранам это поле само по себе не нужно: при включённом режиме
     * ядро не поднимает [noServers], и вся развилка остаётся в одном месте.
     * Держим его затем, чтобы состояние подписки читалось из файла целиком.
     */
    val showZeroHosts: Boolean = false,

    /**
     * Состав конфига: группы и их узлы. Нужен, чтобы показать список серверов
     * ДО подключения — пока туннель не поднят, ядро о группах ничего не знает.
     */
    val groups: List<PanelGroup> = emptyList(),
) {
    /**
     * Поправка к часам устройства в миллисекундах.
     *
     * Измерение старше месяца выбрасывается, а не используется: опасен не уход
     * кварца (секунды в месяц), а то, что человек поправил часы сам или их
     * подтянула синхронизация после загрузки — в этот момент сохранённая
     * поправка превращается в ошибку ровно своего размера. Отрицательный
     * возраст означает то же самое: часы устройства ушли назад под измерением.
     */
    fun clockSkewMillis(): Long {
        if (clockSkew == 0L || clockSkewAt == 0L) return 0

        val age = System.currentTimeMillis() / 1000 - clockSkewAt

        return if (age in 0..MAX_CLOCK_SKEW_AGE_SECONDS) clockSkew * 1000 else 0
    }

    val isEmpty: Boolean
        get() = title.isBlank() && announce.isBlank() && promo.isBlank() &&
            portalUrl.isBlank() && logoFile.isBlank() && groups.isEmpty()
}

private const val MAX_CLOCK_SKEW_AGE_SECONDS = 30L * 24 * 60 * 60

@Serializable
data class PanelGroup(
    val name: String = "",
    val type: String = "",
    val proxies: List<String> = emptyList(),
)
